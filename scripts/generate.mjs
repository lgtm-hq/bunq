import { mkdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const configUrl = new URL("package.json", root);
const config = JSON.parse(await readFile(configUrl, "utf8"));
const { scope, binary, nodeMinimums } = config.bunqWorkspace;
const nodeRange = nodeMinimums.map((version) => `^${version}`).join(" || ");
const clientName = `@${scope}/bunq-client`;
const clientEntry = "runtime";
const packages = [
  {
    directory: "client",
    name: clientName,
    description: "Portable bunq client (workspace foundation; API not implemented)",
    exports: {
      ".": { types: `./dist/${clientEntry}.d.ts`, import: `./dist/${clientEntry}.js` },
      "./package.json": "./package.json",
    },
  },
  {
    directory: "mcp",
    name: `@${scope}/bunq-mcp`,
    description: "bunq MCP adapter (workspace foundation; transport not implemented)",
    exports: { "./package.json": "./package.json" },
    bin: { [binary]: "./dist/cli.js" },
    dependencies: { [clientName]: "workspace:*" },
  },
];

const generatedPaths = [];
async function writeGenerated(path, content) {
  generatedPaths.push(path);
  await writeFile(new URL(path, root), content);
}

async function writeJson(path, value) {
  await writeGenerated(path, `${JSON.stringify(value, null, 2)}\n`);
}

// These are derived artifacts. Edit the root package.json and regenerate.
config.engines = { node: nodeRange, bun: config.packageManager.split("@")[1] };
await writeJson("package.json", config);
await writeGenerated(".bun-version", `${config.engines.bun}\n`);
const sourceConfig = JSON.parse(await readFile(new URL("tsconfig.json", root), "utf8"));
sourceConfig.compilerOptions.paths = {
  [clientName]: [`./packages/client/src/${clientEntry}.ts`],
};
await writeJson("tsconfig.json", sourceConfig);
for (const { directory, ...entry } of packages) {
  await mkdir(new URL(`packages/${directory}/`, root), { recursive: true });
  await writeJson(`packages/${directory}/package.json`, {
    ...entry,
    version: config.version,
    private: true,
    type: "module",
    license: config.license,
    repository: {
      type: "git",
      url: "git+https://github.com/lgtm-hq/bunq.git",
      directory: `packages/${directory}`,
    },
    files: ["dist/*.js", "dist/*.d.ts", "LICENSE", "README.md"],
    engines: { node: nodeRange },
  });
}
await writeGenerated(
  "packages/client/src/runtime-support.ts",
  `// Generated by scripts/generate.mjs from root package.json.\n` +
    `export const NODE_RANGE = ${JSON.stringify(nodeRange)};\n` +
    `export const NODE_MINIMUMS = [\n${nodeMinimums.map((version) => `  [${version.split(".").join(", ")}],`).join("\n")}\n] as const;\n`,
);
await writeGenerated(
  "packages/mcp/src/package-info.ts",
  `// Generated by scripts/generate.mjs from root package.json.\n` +
    `export const PACKAGE_VERSION = ${JSON.stringify(config.version)};\n` +
    `export const BINARY_NAME = ${JSON.stringify(binary)};\n`,
);
await writeFile(
  new URL(".prettierignore", root),
  "# Generated by scripts/generate.mjs; formatters must not rewrite generated metadata.\n" +
    generatedPaths.map((path) => `/${path}`).join("\n") +
    "\n",
);
console.log("Generated workspace metadata from root package.json.");
